/*
 * Throughput benchmark.
 *
 * Each kernel is timed against every baseline that does the same job, not
 * only against this project's own C:
 *
 *   C -O2          the portable references in src/ref, built with the
 *                  library's own flags. This is the baseline tier.
 *   C -O3 native   the same source rebuilt with -O3 -march=native, so the
 *                  compiler may auto-vectorise for the exact host CPU. This is
 *                  the honest answer to "would the compiler have done this?"
 *   libc memchr    for hp_find_byte. glibc's memchr is itself hand written
 *                  SIMD assembly selected at run time.
 *   simdutf        validate_ascii, for hp_is_ascii (make bench-full only).
 *   google crc32c  crc32c::Extend, for hp_crc32c (make bench-full only).
 *
 * and then against the hotpath tiers the host supports. The last two columns
 * name the fastest non-hotpath entry and give hotpath's best tier as a
 * multiple of it, which is the number that answers whether the assembly earns
 * its keep. Where a library wins, that ratio is below one and is printed as
 * it is.
 *
 * Method, and why it is shaped this way. The inner loop count is calibrated per
 * column until one run lasts at least MIN_SECONDS. The columns are then timed
 * in rotation, one run each, for REPEATS rounds, and the fastest run per column
 * is kept. Rotating matters: measuring one column to completion before
 * starting the next lets any drift over the length of the run, from another
 * process waking up or from the clock moving under sustained vector load, land
 * entirely on one column and read as a difference between them. Keeping the
 * fastest rather than the mean matters for the same reason, since contention on
 * a shared machine only ever makes a run slower.
 *
 * Two kernels are shared between the sse42 and avx2 tiers, so those two
 * columns run identical code. Whatever gap remains between them is the noise
 * floor of this machine on this run, which is the reader's check on how much
 * of any other gap in the table to believe.
 *
 * Every column is reached through a function pointer, the way the public entry
 * points reach the kernels, so call overhead is the same for all of them.
 *
 * Output is markdown, so docs/BENCHMARKS.md is regenerated by redirecting
 * this straight into it.
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include "internal.h"
#include "timing.h"

#define MIN_SECONDS 0.12
#define REPEATS 7

/* src/ref rebuilt with NATIVE_OPT, see the bench rules in the Makefile. */
uint32_t    hp_crc32c_native(uint32_t crc, const void *buf, size_t len);
size_t      hp_count_byte_native(const void *buf, size_t len, uint8_t needle);
const void *hp_find_byte_native(const void *buf, size_t len, uint8_t needle);
int         hp_is_ascii_native(const void *buf, size_t len);
void        hp_hex_encode_native(char *dst, const void *src, size_t len);

#if defined(HP_BENCH_LIBS)
/* bench/baselines.cpp */
int         hp_bench_simdutf_is_ascii(const void *buf, size_t len);
uint32_t    hp_bench_google_crc32c(uint32_t crc, const void *buf, size_t len);
const char *hp_bench_simdutf_kernel(void);
#endif

#ifndef HP_NATIVE_FLAGS
#define HP_NATIVE_FLAGS "-O3 -march=native"
#endif

enum {
    K_CRC32C = 0,
    K_COUNT_BYTE,
    K_FIND_BYTE,
    K_IS_ASCII,
    K_HEX_ENCODE,
    K_COUNT
};

static const char *kernel_names[K_COUNT] = {
    "hp_crc32c", "hp_count_byte", "hp_find_byte", "hp_is_ascii", "hp_hex_encode"
};

static const char *kernel_notes[K_COUNT] = {
    "CRC-32C over the whole buffer. The sse42 and avx2 tiers share one kernel.",
    "Counts newlines at roughly one per 64 bytes. No widely used library "
    "exports a byte count, so the comparison is against compiled C only.",
    "The needle is absent, so the whole buffer is scanned.",
    "All ASCII input, so the whole buffer is scanned.",
    "Two output bytes per input byte. The sse42 and avx2 tiers share one "
    "kernel. No library baseline was found that is a fair like for like, so "
    "the comparison is against compiled C only."
};

static const size_t sizes[] = { 64, 256, 1024, 4096, 65536, 1048576, 16777216 };
#define N_SIZES (sizeof(sizes) / sizeof(sizes[0]))

/* -------------------------------------------------------------- columns -- */

static const void *libc_memchr(const void *buf, size_t len, uint8_t needle)
{
    return memchr(buf, needle, len);
}

typedef struct {
    const char   *name;
    int           hotpath;   /* 1 for a hotpath tier, 0 for a baseline     */
    hp_impl_table fn;        /* NULL where the column has no such kernel   */
} column;

#define MAX_COLUMNS 10

static column g_cols[MAX_COLUMNS];
static int g_ncols;

static void add_column(const char *name, int hotpath, const hp_impl_table *fn)
{
    column *c = &g_cols[g_ncols++];
    c->name = name;
    c->hotpath = hotpath;
    c->fn = *fn;
}

static void build_columns(void)
{
    hp_impl_table t;
    int b;

    add_column("C -O2", 0, hp_table_for(HP_BACKEND_BASELINE));

    t.crc32c = hp_crc32c_native;
    t.count_byte = hp_count_byte_native;
    t.find_byte = hp_find_byte_native;
    t.is_ascii = hp_is_ascii_native;
    t.hex_encode = hp_hex_encode_native;
    add_column("C -O3 native", 0, &t);

    memset(&t, 0, sizeof(t));
    t.find_byte = libc_memchr;
    add_column("libc memchr", 0, &t);

#if defined(HP_BENCH_LIBS)
    memset(&t, 0, sizeof(t));
    t.is_ascii = hp_bench_simdutf_is_ascii;
    add_column("simdutf", 0, &t);

    memset(&t, 0, sizeof(t));
    t.crc32c = hp_bench_google_crc32c;
    add_column("google crc32c", 0, &t);
#endif

    for (b = HP_BACKEND_SSE42; b < HP_BACKEND_COUNT; b++) {
        if (hp_backend_supported((hp_backend_t)b)) {
            add_column(hp_backend_name((hp_backend_t)b), 1,
                       hp_table_for((hp_backend_t)b));
        }
    }
}

static int column_has(const column *c, int kernel)
{
    switch (kernel) {
    case K_CRC32C:     return c->fn.crc32c != NULL;
    case K_COUNT_BYTE: return c->fn.count_byte != NULL;
    case K_FIND_BYTE:  return c->fn.find_byte != NULL;
    case K_IS_ASCII:   return c->fn.is_ascii != NULL;
    case K_HEX_ENCODE: return c->fn.hex_encode != NULL;
    default:           return 0;
    }
}

/* ------------------------------------------------------------- timing -- */

static volatile uint32_t sink_u32;
static volatile size_t sink_size;
static volatile int sink_int;
static const void *volatile sink_ptr;

static void call_kernel(const column *c, int kernel, const unsigned char *buf,
                        size_t len, char *hex_dst)
{
    switch (kernel) {
    case K_CRC32C:     sink_u32  = c->fn.crc32c(0, buf, len);        break;
    case K_COUNT_BYTE: sink_size = c->fn.count_byte(buf, len, '\n'); break;
    case K_FIND_BYTE:  sink_ptr  = c->fn.find_byte(buf, len, 0x01);  break;
    case K_IS_ASCII:   sink_int  = c->fn.is_ascii(buf, len);         break;
    case K_HEX_ENCODE: c->fn.hex_encode(hex_dst, buf, len);          break;
    default: break;
    }
}

/* Time one batch of calls and report the elapsed seconds. */
static double time_batch(const column *c, int kernel, const unsigned char *buf,
                         size_t len, char *hex_dst, long long iters)
{
    double t0 = hp_now_seconds();
    long long i;

    for (i = 0; i < iters; i++) {
        call_kernel(c, kernel, buf, len, hex_dst);
    }

    return hp_now_seconds() - t0;
}

/* Grow the batch until it is long enough to time meaningfully. */
static long long calibrate(const column *c, int kernel, const unsigned char *buf,
                      size_t len, char *hex_dst, double min_seconds)
{
    long long iters = 1;

    while (iters < (1LL << 40)) {
        if (time_batch(c, kernel, buf, len, hex_dst, iters) >= min_seconds) {
            break;
        }
        iters *= 2;
    }

    return iters;
}

static void format_size(size_t bytes, char *out, size_t out_len)
{
    if (bytes >= 1048576) {
        snprintf(out, out_len, "%zu MiB", bytes / 1048576);
    } else if (bytes >= 1024) {
        snprintf(out, out_len, "%zu KiB", bytes / 1024);
    } else {
        snprintf(out, out_len, "%zu B", bytes);
    }
}

static void fill_buffer(unsigned char *buf, size_t len)
{
    size_t i;
    uint64_t state = 0x243F6A8885A308D3ULL;

    for (i = 0; i < len; i++) {
        state ^= state >> 12;
        state ^= state << 25;
        state ^= state >> 27;
        /* Printable ASCII keeps hp_is_ascii on its full scan path. */
        buf[i] = (unsigned char)(0x20 + ((state * 0x2545F4914F6CDD1DULL) >> 58));
        if (i % 64 == 63) {
            buf[i] = '\n';
        }
    }
}

/* Every column has to agree with the C reference before any is timed. */
static int cross_check(const unsigned char *buf, size_t len, char *a, char *b)
{
    const column *ref = &g_cols[0];
    int ci;

    for (ci = 1; ci < g_ncols; ci++) {
        const column *c = &g_cols[ci];
        int bad = 0;

        if (c->fn.crc32c) {
            bad |= c->fn.crc32c(0, buf, len) != ref->fn.crc32c(0, buf, len);
        }
        if (c->fn.count_byte) {
            bad |= c->fn.count_byte(buf, len, '\n') != ref->fn.count_byte(buf, len, '\n');
        }
        if (c->fn.find_byte) {
            bad |= c->fn.find_byte(buf, len, '\n') != ref->fn.find_byte(buf, len, '\n');
            bad |= c->fn.find_byte(buf, len, 0x01) != ref->fn.find_byte(buf, len, 0x01);
        }
        if (c->fn.is_ascii) {
            bad |= c->fn.is_ascii(buf, len) != ref->fn.is_ascii(buf, len);
        }
        if (c->fn.hex_encode) {
            c->fn.hex_encode(a, buf, len);
            ref->fn.hex_encode(b, buf, len);
            bad |= memcmp(a, b, 2 * len) != 0;
        }
        if (bad) {
            fprintf(stderr, "bench: %s disagrees with the C reference\n", c->name);
            return 1;
        }
    }
    return 0;
}

static void usage(const char *argv0)
{
    fprintf(stderr, "usage: %s [--quick] [--host=TEXT]\n", argv0);
}

int main(int argc, char **argv)
{
    size_t max_size = sizes[N_SIZES - 1];
    size_t n_sizes = N_SIZES;
    unsigned char *buf;
    char *hex_dst;
    char *hex_check;
    int kernel;
    int quick = 0;
    const char *host = NULL;
    double min_seconds = MIN_SECONDS;
    static double results[K_COUNT][N_SIZES][MAX_COLUMNS];
    long long iters[MAX_COLUMNS];
    int status = 0;
    int i;

    for (i = 1; i < argc; i++) {
        if (strcmp(argv[i], "--quick") == 0) {
            quick = 1;
        } else if (strncmp(argv[i], "--host=", 7) == 0) {
            host = argv[i] + 7;
        } else {
            usage(argv[0]);
            return 2;
        }
    }

    if (quick) {
        /* Enough to prove the harness runs, without the sixteen megabyte pass. */
        n_sizes = 4;
        max_size = sizes[n_sizes - 1];
        min_seconds = 0.01;
    }

    build_columns();

    buf = malloc(max_size);
    hex_dst = malloc(max_size * 2);
    hex_check = malloc(max_size * 2);
    if (buf == NULL || hex_dst == NULL || hex_check == NULL) {
        fprintf(stderr, "out of memory\n");
        status = 1;
        goto done;
    }
    fill_buffer(buf, max_size);

    if (cross_check(buf, max_size < 65536 ? max_size : 65536, hex_dst, hex_check) != 0) {
        status = 1;
        goto done;
    }

    for (kernel = 0; kernel < K_COUNT; kernel++) {
        size_t si;
        for (si = 0; si < n_sizes; si++) {
            int rep;
            int ci;

            for (ci = 0; ci < g_ncols; ci++) {
                iters[ci] = 0;
                if (column_has(&g_cols[ci], kernel)) {
                    iters[ci] = calibrate(&g_cols[ci], kernel, buf, sizes[si],
                                          hex_dst, min_seconds);
                }
            }

            /* Rotate through the columns so drift is shared, not concentrated. */
            for (rep = 0; rep < REPEATS; rep++) {
                for (ci = 0; ci < g_ncols; ci++) {
                    double elapsed, gbps;

                    if (iters[ci] == 0) {
                        continue;
                    }
                    elapsed = time_batch(&g_cols[ci], kernel, buf, sizes[si],
                                         hex_dst, iters[ci]);
                    if (elapsed <= 0.0) {
                        continue;
                    }
                    gbps = ((double)sizes[si] * (double)iters[ci]) / elapsed / 1e9;
                    if (gbps > results[kernel][si][ci]) {
                        results[kernel][si][ci] = gbps;
                    }
                }
            }
        }
    }

    printf("# Benchmarks\n\n");
    printf("CPU: %s\n\n", hp_cpu()->brand[0] ? hp_cpu()->brand : "unknown");
    if (host != NULL) {
        printf("Host: %s\n\n", host);
    }
#if defined(__clang__)
    printf("Compiler: clang %s\n\n", __clang_version__);
#elif defined(__GNUC__)
    printf("Compiler: gcc %s\n\n", __VERSION__);
#endif
#if defined(HP_BENCH_LIBS)
    printf("simdutf selected its `%s` kernel on this CPU.\n\n", hp_bench_simdutf_kernel());
#else
    printf("Built without the third party libraries; `make bench-full` adds them.\n\n");
#endif
    printf("Throughput in GB/s, higher is better, measured on the machine named\n"
           "above and true of nowhere else. The columns before the hotpath tiers\n"
           "are baselines: the project's own C at -O2, the same C rebuilt with\n"
           "`%s`, and established libraries where one does the\n"
           "same job. The last two columns name the fastest baseline and give\n"
           "hotpath's fastest tier as a multiple of it, so a figure below 1.00x\n"
           "means the baseline wins.\n\n", HP_NATIVE_FLAGS);
    printf("Two of the kernels are shared between the sse42 and avx2 tiers,\n"
           "as noted under each heading. The gap between two columns that run\n"
           "identical code is pure measurement noise, so it doubles as a read\n"
           "on how much of any other gap in the table is real.\n\n");
    if (hp_backend_supported(HP_BACKEND_AVX512)) {
        printf("This CPU reports AVX-512, so the avx512 tier is timed as well.\n\n");
    } else {
        printf("This CPU has no AVX-512, so the avx512 tier is absent here. It is\n"
               "verified for correctness under Intel SDE in CI and has never been\n"
               "timed.\n\n");
    }

    for (kernel = 0; kernel < K_COUNT; kernel++) {
        size_t si;
        int ci;

        printf("## %s\n\n", kernel_names[kernel]);
        printf("%s\n\n", kernel_notes[kernel]);
        printf("| size |");
        for (ci = 0; ci < g_ncols; ci++) {
            if (column_has(&g_cols[ci], kernel)) {
                printf(" %s |", g_cols[ci].name);
            }
        }
        printf(" best baseline | hotpath vs best baseline |\n");
        printf("| ---: |");
        for (ci = 0; ci < g_ncols; ci++) {
            if (column_has(&g_cols[ci], kernel)) {
                printf(" ---: |");
            }
        }
        printf(" --- | ---: |\n");

        for (si = 0; si < n_sizes; si++) {
            char label[32];
            double best_base = 0.0;
            double best_hp = 0.0;
            const char *best_base_name = "none";

            format_size(sizes[si], label, sizeof(label));
            printf("| %s |", label);
            for (ci = 0; ci < g_ncols; ci++) {
                double r = results[kernel][si][ci];
                if (!column_has(&g_cols[ci], kernel)) {
                    continue;
                }
                printf(" %.2f |", r);
                if (g_cols[ci].hotpath) {
                    if (r > best_hp) {
                        best_hp = r;
                    }
                } else if (r > best_base) {
                    best_base = r;
                    best_base_name = g_cols[ci].name;
                }
            }
            if (best_base > 0.0 && best_hp > 0.0) {
                printf(" %s | %.2fx |\n", best_base_name, best_hp / best_base);
            } else {
                printf(" %s | n/a |\n", best_base_name);
            }
        }
        printf("\n");
    }

done:
    free(buf);
    free(hex_dst);
    free(hex_check);
    return status;
}
