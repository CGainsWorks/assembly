/*
 * Throughput benchmark.
 *
 * Each kernel is timed at every dispatch tier the host supports, so the number
 * that matters, the speedup over portable C on the same machine with the same
 * compiler and the same data, falls out directly. The reference implementations
 * are built with the same optimisation flags as everything else and the
 * compiler is free to vectorise them, which is the honest comparison.
 *
 * Method, and why it is shaped this way. The inner loop count is calibrated per
 * tier until one run lasts at least MIN_SECONDS. The tiers are then timed in
 * rotation, one run each, for REPEATS rounds, and the fastest run per tier is
 * kept. Rotating matters: measuring one tier to completion before starting the
 * next lets any drift over the length of the run, from another process waking
 * up or from the clock moving under sustained vector load, land entirely on one
 * column and read as a difference between tiers. Keeping the fastest rather
 * than the mean matters for the same reason, since contention on a shared
 * machine only ever makes a run slower.
 *
 * Two kernels are shared between the sse42 and avx2 tiers, so those two columns
 * run identical code. Whatever gap remains between them is the noise floor of
 * this machine on this run, which is the reader's check on how much of any
 * other gap in the table to believe.
 *
 * Output is a markdown table, so docs/BENCHMARKS.md is regenerated by
 * redirecting this straight into it.
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <time.h>

#include "internal.h"

#define MIN_SECONDS 0.12
#define REPEATS 7

enum {
    K_CRC32C = 0,
    K_COUNT_BYTE,
    K_FIND_BYTE,
    K_IS_ASCII,
    K_HEX_ENCODE,
    K_COUNT
};

static const char *kernel_names[K_COUNT] = {
    "hp_crc32c", "hp_count_byte", "hp_find_byte", "hp_is_ascii", "hp_hex_encode"
};

static const char *kernel_notes[K_COUNT] = {
    "CRC-32C over the whole buffer. The sse42 and avx2 tiers share one kernel.",
    "Counts newlines at roughly one per 64 bytes.",
    "The needle is absent, so the whole buffer is scanned.",
    "All ASCII input, so the whole buffer is scanned.",
    "Two output bytes per input byte. The sse42 and avx2 tiers share one kernel."
};

static const size_t sizes[] = { 64, 256, 1024, 4096, 65536, 1048576, 16777216 };
#define N_SIZES (sizeof(sizes) / sizeof(sizes[0]))

static volatile uint32_t sink_u32;
static volatile size_t sink_size;
static volatile int sink_int;
static const void *volatile sink_ptr;

static double now_seconds(void)
{
    struct timespec ts;
    clock_gettime(CLOCK_MONOTONIC, &ts);
    return (double)ts.tv_sec + (double)ts.tv_nsec * 1e-9;
}

static void call_kernel(int kernel, const unsigned char *buf, size_t len,
                        char *hex_dst)
{
    switch (kernel) {
    case K_CRC32C:     sink_u32  = hp_crc32c(0, buf, len);        break;
    case K_COUNT_BYTE: sink_size = hp_count_byte(buf, len, '\n'); break;
    case K_FIND_BYTE:  sink_ptr  = hp_find_byte(buf, len, 0x01);  break;
    case K_IS_ASCII:   sink_int  = hp_is_ascii(buf, len);         break;
    case K_HEX_ENCODE: hp_hex_encode(hex_dst, buf, len);          break;
    default: break;
    }
}

/* Time one batch of calls and report the elapsed seconds. */
static double time_batch(int kernel, const unsigned char *buf, size_t len,
                         char *hex_dst, long iters)
{
    double t0 = now_seconds();
    long i;

    for (i = 0; i < iters; i++) {
        call_kernel(kernel, buf, len, hex_dst);
    }

    return now_seconds() - t0;
}

/* Grow the batch until it is long enough to time meaningfully. */
static long calibrate(int kernel, const unsigned char *buf, size_t len,
                      char *hex_dst)
{
    long iters = 1;

    while (iters < (1L << 40)) {
        if (time_batch(kernel, buf, len, hex_dst, iters) >= MIN_SECONDS) {
            break;
        }
        iters *= 2;
    }

    return iters;
}

static void format_size(size_t bytes, char *out, size_t out_len)
{
    if (bytes >= 1048576) {
        snprintf(out, out_len, "%zu MiB", bytes / 1048576);
    } else if (bytes >= 1024) {
        snprintf(out, out_len, "%zu KiB", bytes / 1024);
    } else {
        snprintf(out, out_len, "%zu B", bytes);
    }
}

static void fill_buffer(unsigned char *buf, size_t len)
{
    size_t i;
    uint64_t state = 0x243F6A8885A308D3ULL;

    for (i = 0; i < len; i++) {
        state ^= state >> 12;
        state ^= state << 25;
        state ^= state >> 27;
        /* Printable ASCII keeps hp_is_ascii on its full scan path. */
        buf[i] = (unsigned char)(0x20 + ((state * 0x2545F4914F6CDD1DULL) >> 58));
        if (i % 64 == 63) {
            buf[i] = '\n';
        }
    }
}

int main(int argc, char **argv)
{
    size_t max_size = sizes[N_SIZES - 1];
    size_t n_sizes = N_SIZES;
    unsigned char *buf;
    char *hex_dst;
    int kernel;
    int backend;
    int quick = 0;
    static double results[K_COUNT][N_SIZES][HP_BACKEND_COUNT];
    long iters[HP_BACKEND_COUNT];
    int i;

    for (i = 1; i < argc; i++) {
        if (strcmp(argv[i], "--quick") == 0) {
            quick = 1;
        } else {
            fprintf(stderr, "usage: %s [--quick]\n", argv[0]);
            return 2;
        }
    }

    if (quick) {
        /* Enough to prove the harness runs, without the sixteen megabyte pass. */
        n_sizes = 4;
        max_size = sizes[n_sizes - 1];
    }

    buf = malloc(max_size);
    hex_dst = malloc(max_size * 2);
    if (buf == NULL || hex_dst == NULL) {
        fprintf(stderr, "out of memory\n");
        free(buf);
        free(hex_dst);
        return 1;
    }
    fill_buffer(buf, max_size);

    for (kernel = 0; kernel < K_COUNT; kernel++) {
        size_t si;
        for (si = 0; si < n_sizes; si++) {
            int rep;

            for (backend = 0; backend < HP_BACKEND_COUNT; backend++) {
                iters[backend] = 0;
                if (!hp_backend_supported((hp_backend_t)backend)) {
                    continue;
                }
                hp_set_backend((hp_backend_t)backend);
                iters[backend] = calibrate(kernel, buf, sizes[si], hex_dst);
            }

            /* Rotate through the tiers so drift is shared, not concentrated. */
            for (rep = 0; rep < REPEATS; rep++) {
                for (backend = 0; backend < HP_BACKEND_COUNT; backend++) {
                    double elapsed, gbps;

                    if (iters[backend] == 0) {
                        continue;
                    }
                    hp_set_backend((hp_backend_t)backend);
                    elapsed = time_batch(kernel, buf, sizes[si], hex_dst,
                                         iters[backend]);
                    if (elapsed <= 0.0) {
                        continue;
                    }
                    gbps = ((double)sizes[si] * (double)iters[backend])
                           / elapsed / 1e9;
                    if (gbps > results[kernel][si][backend]) {
                        results[kernel][si][backend] = gbps;
                    }
                }
            }
        }
    }

    printf("# Benchmarks\n\n");
    printf("CPU: %s\n\n", hp_cpu()->brand[0] ? hp_cpu()->brand : "unknown");
    printf("Throughput in GB/s, higher is better. Every column is the same\n"
           "build and the same data, only the dispatch tier differs. Numbers\n"
           "come from one desktop machine and are meant for comparing the\n"
           "columns against each other, not for comparing machines.\n\n");
    printf("Two of the kernels are shared between the sse42 and avx2 tiers,\n"
           "as noted under each heading. The gap between two columns that run\n"
           "identical code is pure measurement noise, so it doubles as a read\n"
           "on how much of any other gap in the table is real.\n\n");

    for (kernel = 0; kernel < K_COUNT; kernel++) {
        size_t si;
        printf("## %s\n\n", kernel_names[kernel]);
        printf("%s\n\n", kernel_notes[kernel]);
        printf("| size |");
        for (backend = 0; backend < HP_BACKEND_COUNT; backend++) {
            if (hp_backend_supported((hp_backend_t)backend)) {
                printf(" %s |", hp_backend_name((hp_backend_t)backend));
            }
        }
        printf(" best speedup |\n");
        printf("| ---: |");
        for (backend = 0; backend < HP_BACKEND_COUNT; backend++) {
            if (hp_backend_supported((hp_backend_t)backend)) {
                printf(" ---: |");
            }
        }
        printf(" ---: |\n");

        for (si = 0; si < n_sizes; si++) {
            char label[32];
            double baseline = results[kernel][si][HP_BACKEND_BASELINE];
            double best = baseline;

            format_size(sizes[si], label, sizeof(label));
            printf("| %s |", label);
            for (backend = 0; backend < HP_BACKEND_COUNT; backend++) {
                if (!hp_backend_supported((hp_backend_t)backend)) {
                    continue;
                }
                printf(" %.2f |", results[kernel][si][backend]);
                if (results[kernel][si][backend] > best) {
                    best = results[kernel][si][backend];
                }
            }
            if (baseline > 0.0) {
                printf(" %.2fx |\n", best / baseline);
            } else {
                printf(" n/a |\n");
            }
        }
        printf("\n");
    }

    free(buf);
    free(hex_dst);
    return 0;
}
